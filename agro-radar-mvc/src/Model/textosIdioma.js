const PATRONES_EN = [
  [/NASA POWER respondio con el estado (\d+)\./g, "NASA POWER responded with status $1."],
];

export function traducirTextoDinamico(texto, idioma) {
  if (!texto || idioma !== "en") return texto;
  let res = String(texto);

  for (const [es, en] of REEMPLAZOS_EN) {
    res = res.replaceAll(es, en);
  }
  for (const [patron, en] of PATRONES_EN) {
    res = res.replace(patron, en);
  }
  return res;
}

