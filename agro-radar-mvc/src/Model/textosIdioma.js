/**
 * Traduce la explicación climática armada por el controller
 * (incluye nombres de meses y conectores que no conviene
 * reemplazar en el diccionario general).
 */
export function traducirContextoClimatico(texto, idioma = "es") {
  if (!texto) {
    return idioma === "en"
      ? "NASA POWER did not return historical information for the current month."
      : "NASA POWER no devolvió información histórica para el mes actual.";
  }

  if (idioma !== "en") return texto;

  let traducido = String(texto);

  Object.entries(MESES_EN).forEach(([mesEs, mesEn]) => {
    traducido = traducido.replace(new RegExp(`\\b${mesEs}\\b`, "g"), mesEn);
  });

  REEMPLAZOS_CLIMA_EN.forEach(([es, en]) => {
    traducido = traducido.split(es).join(en);
  });

  return traducido;
}